import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsBoolean,
  IsDateString,
  IsIn,
  IsOptional,
  IsString,
  Matches,
  MaxLength,
} from 'class-validator';

const PERMISSION_STATES = ['GRANTED', 'DENIED', 'UNDETERMINED', 'UNAVAILABLE'] as const;
const CONNECTIVITY_STATES = ['ONLINE', 'LIMITED', 'OFFLINE'] as const;
const PLATFORMS = ['android', 'ios', 'web'] as const;

export class ReportReadinessDto {
  @ApiProperty({ description: 'Random per-install identifier generated by the app', example: 'k3f9x2m1q8w7e6r5' })
  @IsString()
  @Matches(/^[A-Za-z0-9_-]{8,64}$/, { message: 'deviceId must be 8-64 letters, digits, "-" or "_"' })
  deviceId!: string;

  @ApiProperty({ enum: PLATFORMS })
  @IsIn(PLATFORMS)
  platform!: (typeof PLATFORMS)[number];

  @ApiPropertyOptional({ example: '0.1.0' })
  @IsOptional()
  @IsString()
  @MaxLength(32)
  appVersion?: string;

  @ApiProperty({ enum: PERMISSION_STATES })
  @IsIn(PERMISSION_STATES)
  locationPermission!: (typeof PERMISSION_STATES)[number];

  @ApiProperty()
  @IsBoolean()
  locationServicesEnabled!: boolean;

  @ApiProperty({ enum: PERMISSION_STATES })
  @IsIn(PERMISSION_STATES)
  notificationPermission!: (typeof PERMISSION_STATES)[number];

  @ApiProperty({ enum: PERMISSION_STATES })
  @IsIn(PERMISSION_STATES)
  cameraPermission!: (typeof PERMISSION_STATES)[number];

  @ApiProperty()
  @IsBoolean()
  motionSensorAvailable!: boolean;

  @ApiProperty({ enum: CONNECTIVITY_STATES })
  @IsIn(CONNECTIVITY_STATES)
  connectivity!: (typeof CONNECTIVITY_STATES)[number];

  @ApiPropertyOptional({ example: 'wifi' })
  @IsOptional()
  @IsString()
  @MaxLength(20)
  connectionType?: string;

  @ApiProperty({ description: 'When the device ran the check (ISO 8601)' })
  @IsDateString()
  checkedAt!: string;
}
