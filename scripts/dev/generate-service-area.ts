// Regenerates shared/src/maps/service-area.data.ts (the facility service-area polygon)
// from the pinned geoBoundaries PHL ADM2 release. Data only: the helpers live in the
// hand-written shared/src/maps/service-area.ts and are never touched by this script.
//
// Run from the repo root: backend/node_modules/.bin/ts-node scripts/dev/generate-service-area.ts
import { writeFile } from 'node:fs/promises';

const COMMIT = '9469f09592ced973a3448cf66b6100b741b64c0d';
const SOURCE_URL =
  `https://media.githubusercontent.com/media/wmgeolab/geoBoundaries/${COMMIT}/` +
  'releaseData/gbOpen/PHL/ADM2/geoBoundaries-PHL-ADM2_simplified.geojson';
const OUTPUT = 'shared/src/maps/service-area.data.ts';

type Feature = {
  properties?: { shapeName?: string };
  geometry?: { type: string; coordinates: unknown };
};

export function renderServiceAreaData(source: string, ring: readonly (readonly [number, number])[]): string {
  return (
    '// GENERATED by scripts/dev/generate-service-area.ts. Do not edit by hand.\n\n' +
    `export const FACILITY_SERVICE_AREA_SOURCE =\n  ${JSON.stringify(source)};\n\n` +
    'export const FACILITY_SERVICE_AREA: readonly (readonly [number, number])[] = [\n' +
    ring.map(([lng, lat]) => `  [${lng}, ${lat}],\n`).join('') +
    '];\n'
  );
}

async function main(): Promise<void> {
  const response = await fetch(SOURCE_URL);
  if (!response.ok) {
    throw new Error(`geoBoundaries download failed: ${response.status} ${response.statusText}`);
  }

  const collection = (await response.json()) as { features?: Feature[] };
  const feature = collection.features?.find(
    (candidate) => candidate.properties?.shapeName === 'Bulacan',
  );
  if (!feature || feature.geometry?.type !== 'Polygon') {
    throw new Error('Bulacan ADM2 polygon was not found');
  }

  const rings = feature.geometry.coordinates as [number, number][][];
  const ring = rings[0];
  if (!ring?.length) {
    throw new Error('Bulacan ADM2 polygon has no exterior ring');
  }

  const source =
    `geoBoundaries PHL-ADM2 Bulacan (simplified; commit ${COMMIT}; CC BY 3.0 IGO): ` + SOURCE_URL;
  await writeFile(OUTPUT, renderServiceAreaData(source, ring));
  console.log(`Wrote ${OUTPUT} with ${ring.length} points`);
}

if (require.main === module) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
