#!/usr/bin/env node
/**
 * Generates the SQL that loads the 19 Bocaue barangay boundaries into
 * `geo_regions` (BARANGAY_ALERT_AUTOMATION_PLAN.md, Phase 1).
 *
 * Input : docs/automation/bocaue-barangay-boundaries.osm.geojson
 * Output: INSERT ... ON CONFLICT statements on stdout (or --out <file>).
 *
 *   node scripts/db/generate-barangay-regions.cjs --out regions.sql
 *
 * The output is pasted into the barangay_coordination migration once, so a
 * production `prisma migrate deploy` needs no data files and no network.
 * Re-run it only when the boundaries change, and put the new SQL in a NEW
 * migration (never edit an applied one).
 *
 * Data: © OpenStreetMap contributors, ODbL 1.0. Keep the attribution.
 *
 * Re-fetching the source data (needs network; run rarely, be polite to the servers):
 *   1. Overpass: relation ids
 *        [out:json];area["name"="Bocaue"]["boundary"="administrative"]->.a;
 *        rel(area.a)["boundary"="administrative"]["admin_level"="10"];out ids tags;
 *   2. Nominatim: https://nominatim.openstreetmap.org/lookup?osm_ids=R...,R...
 *        &format=geojson&polygon_geojson=1&polygon_threshold=0
 *   3. Map each feature name to its barangay_id, keep properties
 *      { barangay_id, name, osm_type, osm_id }, and save over the geojson file.
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..', '..');
const geojsonPath = path.join(root, 'docs/automation/bocaue-barangay-boundaries.osm.geojson');
const hotlinesPath = path.join(root, 'docs/automation/bocaue-barangay-hotlines.json');

const sql = (s) => `'${String(s).replace(/'/g, "''")}'`;

const boundaries = JSON.parse(fs.readFileSync(geojsonPath, 'utf8'));
const directory = JSON.parse(fs.readFileSync(hotlinesPath, 'utf8'));

// The directory and the boundaries must describe exactly the same 19 barangays.
const boundaryIds = boundaries.features.map((f) => f.properties.barangay_id).sort();
const directoryIds = directory.barangays.map((b) => b.barangay_id).sort();
if (JSON.stringify(boundaryIds) !== JSON.stringify(directoryIds)) {
  console.error('Barangay ids differ between the boundaries file and the hotline directory.');
  console.error('boundaries:', boundaryIds.join(','));
  console.error('directory :', directoryIds.join(','));
  process.exit(1);
}
if (new Set(boundaryIds).size !== boundaryIds.length) {
  console.error('Duplicate barangay_id in the boundaries file.');
  process.exit(1);
}

const rows = boundaries.features.map((f) => {
  if (f.geometry.type !== 'Polygon' && f.geometry.type !== 'MultiPolygon') {
    throw new Error(`${f.properties.barangay_id}: unexpected geometry ${f.geometry.type}`);
  }
  // MakeValid can return a collection; keep only the polygon parts, as one MultiPolygon.
  const geom =
    `ST_Multi(ST_CollectionExtract(ST_MakeValid(ST_SetSRID(ST_GeomFromGeoJSON(` +
    `${sql(JSON.stringify(f.geometry))}), 4326)), 3))`;
  return `  (${sql(f.properties.barangay_id)}, ${sql(f.properties.name)}, 'barangay', ${geom}, now())`;
});

const out = [
  '-- Bocaue barangay boundaries (19). Generated by scripts/db/generate-barangay-regions.cjs',
  '-- Data (c) OpenStreetMap contributors, ODbL 1.0 (https://www.openstreetmap.org/copyright).',
  'INSERT INTO "geo_regions" ("id", "name", "region_type", "boundary", "last_updated_at") VALUES',
  rows.join(',\n'),
  'ON CONFLICT ("id") DO UPDATE SET',
  '  "name" = EXCLUDED."name",',
  '  "region_type" = EXCLUDED."region_type",',
  '  "boundary" = EXCLUDED."boundary",',
  '  "last_updated_at" = now();',
  '',
].join('\n');

const outIdx = process.argv.indexOf('--out');
if (outIdx !== -1 && process.argv[outIdx + 1]) {
  fs.writeFileSync(process.argv[outIdx + 1], out);
  console.error(`wrote ${rows.length} rows to ${process.argv[outIdx + 1]}`);
} else {
  process.stdout.write(out);
}
