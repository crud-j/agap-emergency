import React, { useState } from 'react';
import {
  View, Text, StyleSheet, ScrollView, TouchableOpacity, ActivityIndicator, Alert,
} from 'react-native';
import { Ionicons } from '@expo/vector-icons';
import { requireOptionalNativeModule } from 'expo';
import * as FileSystem from 'expo-file-system/legacy';
import { useQuery, useMutation, useQueryClient } from '@tanstack/react-query';
import { ScreenHeader } from '../../src/components/ui/screen-header';
import {
  checkConsent, grantConsent, revokeConsent, getAccessLog, exportMyData,
  MEDICAL_CONSENT_TYPE, type AccessLogEntry,
} from '../../src/services/api/consent.api';

type ExportFormat = 'csv' | 'pdf';
type ExportField = [string, string];

class MissingNativeModuleError extends Error {}

// Importing expo-sharing / expo-print in a dev client built before they were added
// throws during module evaluation, which Metro reports as a fatal error even inside try/catch.
function assertNativeModules(format: ExportFormat) {
  const required = format === 'pdf' ? ['ExpoSharing', 'ExpoPrint'] : ['ExpoSharing'];
  if (required.some((name) => !requireOptionalNativeModule(name))) {
    throw new MissingNativeModuleError();
  }
}

function flattenExportData(value: unknown, path = ''): ExportField[] {
  if (Array.isArray(value)) {
    if (value.length === 0) return [[path || 'Data', '[]']];
    return value.flatMap((item, index) => flattenExportData(item, `${path}[${index}]`));
  }

  if (value !== null && typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return [[path || 'Data', '{}']];
    return entries.flatMap(([key, item]) =>
      flattenExportData(item, path ? `${path}.${key}` : key),
    );
  }

  const text = value === null || value === undefined ? '' : String(value);
  return [[path || 'Data', text]];
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function csvCell(value: string): string {
  const safeValue = /^[\t\r ]*[=+\-@]/.test(value) ? `'${value}` : value;
  return `"${safeValue.replace(/"/g, '""')}"`;
}

function createExportHtml(fields: ExportField[]): string {
  const rows = fields.map(([field, value]) =>
    `<tr><th>${escapeHtml(field)}</th><td>${escapeHtml(value)}</td></tr>`,
  ).join('');

  return `<!doctype html>
<html>
  <head>
    <meta charset="utf-8">
    <style>
      body { color: #172923; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif; padding: 20px; }
      h1 { color: #0d6053; font-size: 22px; margin: 0 0 6px; }
      p { color: #64746d; font-size: 11px; margin: 0 0 20px; }
      table { border-collapse: collapse; font-size: 11px; width: 100%; }
      th, td { border-bottom: 1px solid #e1e9e5; padding: 9px 8px; text-align: left; vertical-align: top; }
      th { color: #40534b; font-weight: 700; width: 36%; word-break: break-word; }
      td { color: #263a32; word-break: break-word; }
      tr { page-break-inside: avoid; }
    </style>
  </head>
  <body>
    <h1>AGAP Citizen Data Export</h1>
    <p>Personal data export generated by AGAP. Keep this document private.</p>
    <table><tbody>${rows}</tbody></table>
  </body>
</html>`;
}

// MOD-48 — Privacy, Consent and Medical Data Protection.
export default function PrivacyScreen() {
  const qc = useQueryClient();
  const [exporting, setExporting] = useState<ExportFormat | null>(null);

  const consent = useQuery({
    queryKey: ['consent', MEDICAL_CONSENT_TYPE],
    queryFn: () => checkConsent(MEDICAL_CONSENT_TYPE),
  });

  const log = useQuery({
    queryKey: ['privacy-access-log'],
    queryFn: getAccessLog,
  });

  const grant = useMutation({
    mutationFn: () => grantConsent(MEDICAL_CONSENT_TYPE),
    onSuccess: () => qc.invalidateQueries({ queryKey: ['consent', MEDICAL_CONSENT_TYPE] }),
    onError: (e: unknown) => Alert.alert('Could not grant consent', e instanceof Error ? e.message : 'Please try again.'),
  });

  const revoke = useMutation({
    mutationFn: () => revokeConsent(MEDICAL_CONSENT_TYPE),
    onSuccess: () => qc.invalidateQueries({ queryKey: ['consent', MEDICAL_CONSENT_TYPE] }),
    onError: (e: unknown) => Alert.alert('Could not withdraw consent', e instanceof Error ? e.message : 'Please try again.'),
  });

  function confirmRevoke() {
    Alert.alert(
      'Withdraw medical data consent?',
      'Responders will no longer be able to view your medical profile in an emergency. You can grant it again anytime.',
      [
        { text: 'Cancel', style: 'cancel' },
        { text: 'Withdraw', style: 'destructive', onPress: () => revoke.mutate() },
      ],
    );
  }

  async function handleExport(format: ExportFormat) {
    setExporting(format);
    try {
      assertNativeModules(format);
      const sharing = await import('expo-sharing');
      if (!(await sharing.isAvailableAsync())) {
        throw new Error('File sharing is unavailable on this device.');
      }

      const payload = await exportMyData();
      const fields = flattenExportData(payload);
      if (fields.length === 0) fields.push(['Data', 'No data available']);
      const filename = `agap-citizen-data-${new Date().toISOString().replace(/[:.]/g, '-')}`;
      const directory = FileSystem.documentDirectory;
      if (!directory) throw new Error('Could not access device storage to create the export.');

      let fileUri: string;
      let mimeType: string;
      let uti: string;
      if (format === 'csv') {
        const csv = [
          ['Field', 'Value'].map(csvCell).join(','),
          ...fields.map((field) => field.map(csvCell).join(',')),
        ].join('\r\n');
        fileUri = `${directory}${filename}.csv`;
        await FileSystem.writeAsStringAsync(fileUri, `\uFEFF${csv}`, { encoding: 'utf8' });
        mimeType = 'text/csv';
        uti = 'public.comma-separated-values-text';
      } else {
        const print = await import('expo-print');
        const pdf = await print.printToFileAsync({
          html: createExportHtml(fields),
          margins: { top: 36, right: 36, bottom: 36, left: 36 },
        });
        fileUri = `${directory}${filename}.pdf`;
        await FileSystem.copyAsync({ from: pdf.uri, to: fileUri });
        mimeType = 'application/pdf';
        uti = 'com.adobe.pdf';
      }

      await sharing.shareAsync(fileUri, {
        mimeType,
        UTI: uti,
        dialogTitle: `Export citizen data as ${format.toUpperCase()}`,
      });
    } catch (e) {
      const message = e instanceof Error ? e.message : 'Please try again.';
      const needsNativeRebuild =
        e instanceof MissingNativeModuleError || message.includes('Cannot find native module');
      Alert.alert(
        needsNativeRebuild ? 'Update required' : 'Export failed',
        needsNativeRebuild
          ? 'This installed app does not include the file export module. Rebuild and reinstall the Android app, then try again.'
          : message,
      );
    } finally {
      setExporting(null);
    }
  }

  const granted = consent.data?.granted ?? false;

  return (
    <View style={styles.root}>
      <ScreenHeader title="Privacy & Consent" />
      <ScrollView contentContainerStyle={{ padding: 16, paddingBottom: 32 }}>
        {/* Medical data consent (MOD-48) */}
        <View style={styles.card}>
          <View style={styles.cardHead}>
            <View style={[styles.iconWrap, { backgroundColor: granted ? '#E7F6F1' : '#FEF3F2' }]}>
              <Ionicons name={granted ? 'shield-checkmark' : 'shield-outline'} size={22} color={granted ? '#0D6053' : '#B42318'} />
            </View>
            <View style={{ flex: 1 }}>
              <Text style={styles.cardTitle}>Medical Data Sharing</Text>
              <Text style={styles.cardSub}>
                {consent.isLoading
                  ? 'Checking…'
                  : granted
                    ? 'Granted — responders can view your medical profile during an emergency.'
                    : 'Not granted — your medical profile is hidden from responders.'}
              </Text>
            </View>
          </View>

          <Text style={styles.legal}>
            Your blood type, allergies, and conditions are sensitive medical data. We only reveal
            them to responders assigned to your active incident, and every access is logged below.
          </Text>

          {granted ? (
            <TouchableOpacity
              style={[styles.btn, styles.btnDanger]}
              onPress={confirmRevoke}
              disabled={revoke.isPending}
              activeOpacity={0.85}
            >
              {revoke.isPending
                ? <ActivityIndicator color="#B42318" />
                : <Text style={styles.btnDangerText}>Withdraw Consent</Text>}
            </TouchableOpacity>
          ) : (
            <TouchableOpacity
              style={[styles.btn, styles.btnPrimary]}
              onPress={() => grant.mutate()}
              disabled={grant.isPending}
              activeOpacity={0.85}
            >
              {grant.isPending
                ? <ActivityIndicator color="#FFFFFF" />
                : <Text style={styles.btnPrimaryText}>Grant Consent</Text>}
            </TouchableOpacity>
          )}
        </View>

        {/* Data export */}
        <View style={styles.card}>
          <View style={styles.cardHead}>
            <View style={[styles.iconWrap, { backgroundColor: '#EFF6FF' }]}>
              <Ionicons name="download-outline" size={22} color="#1D4ED8" />
            </View>
            <View style={{ flex: 1 }}>
              <Text style={styles.cardTitle}>Export My Data</Text>
              <Text style={styles.cardSub}>Create a portable copy of your profile, contacts, and consent history.</Text>
            </View>
          </View>
          <View style={styles.exportActions}>
            <TouchableOpacity
              style={[styles.btn, styles.btnSecondary, styles.exportBtn]}
              onPress={() => handleExport('csv')}
              disabled={exporting !== null}
              activeOpacity={0.85}
              accessibilityRole="button"
              accessibilityLabel="Export citizen data as CSV"
            >
              {exporting === 'csv'
                ? <ActivityIndicator color="#0D6053" />
                : <>
                    <Ionicons name="grid-outline" size={17} color="#0D6053" />
                    <Text style={styles.btnSecondaryText}>CSV</Text>
                  </>}
            </TouchableOpacity>
            <TouchableOpacity
              style={[styles.btn, styles.btnSecondary, styles.exportBtn]}
              onPress={() => handleExport('pdf')}
              disabled={exporting !== null}
              activeOpacity={0.85}
              accessibilityRole="button"
              accessibilityLabel="Export citizen data as PDF"
            >
              {exporting === 'pdf'
                ? <ActivityIndicator color="#0D6053" />
                : <>
                    <Ionicons name="document-text-outline" size={17} color="#0D6053" />
                    <Text style={styles.btnSecondaryText}>PDF</Text>
                  </>}
            </TouchableOpacity>
          </View>
          <Text style={styles.exportNote}>Your export contains personal information. Share it only with trusted recipients.</Text>
        </View>

        {/* Access log */}
        <Text style={styles.sectionTitle}>Access Log</Text>
        <Text style={styles.sectionSub}>Who viewed your sensitive data, most recent first.</Text>

        {log.isLoading ? (
          <ActivityIndicator color="#0D6053" style={{ marginTop: 16 }} />
        ) : (log.data?.length ?? 0) === 0 ? (
          <View style={styles.emptyLog}>
            <Ionicons name="lock-closed-outline" size={28} color="#9CA3AF" />
            <Text style={styles.emptyText}>No one has accessed your sensitive data.</Text>
          </View>
        ) : (
          (log.data ?? []).map((entry: AccessLogEntry) => (
            <View key={entry.id} style={styles.logRow}>
              <Ionicons name="eye-outline" size={16} color="#6B7280" style={{ marginRight: 10, marginTop: 2 }} />
              <View style={{ flex: 1 }}>
                <Text style={styles.logType}>{entry.data_type.replace(/_/g, ' ')}</Text>
                {entry.purpose ? <Text style={styles.logPurpose}>{entry.purpose}</Text> : null}
                {entry.accessor_role ? (
                  <Text style={styles.logPurpose}>By: {entry.accessor_role.replace(/_/g, ' ').toLowerCase()}</Text>
                ) : null}
                <Text style={styles.logTime}>{new Date(entry.accessed_at).toLocaleString()}</Text>
              </View>
            </View>
          ))
        )}
      </ScrollView>
    </View>
  );
}

